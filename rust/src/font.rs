#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_glyph_is_well_formed() {
        for (font, w_ok) in [(&SMALL, &[5usize][..]), (&BIG, &[5, 7, 8][..])] {
            for (c, g) in font.glyphs {
                let rows: Vec<&str> = g.split(' ').collect();
                assert_eq!(rows.len() as i32, font.height, "{c:?}");
                assert!(
                    rows.iter().all(|r| r.len() == rows[0].len() && r.bytes().all(|b| b == b'#' || b == b'.')),
                    "{c:?}"
                );
                assert!(w_ok.contains(&rows[0].len()), "{c:?}");
            }
        }
        for c in ' '..='~' {
            assert!(SMALL.glyphs.iter().any(|g| g.0 == c), "{c:?}");
        }
        for c in "0123456789%-".chars() {
            assert!(BIG.glyphs.iter().any(|g| g.0 == c), "{c:?}");
        }
    }

    #[test]
    fn layout() {
        assert_eq!(SMALL.width("WORM", true), 4 * 6 + 3);
        assert_eq!(SMALL.width("right-click", false), 11 * 6 - 1);
        assert_eq!(BIG.width("100%", false), 3 * 7 + 8 + 3);
        assert_eq!(BIG.width("", false), 0);
        assert_eq!(SMALL.runs("-", 10, 20, false), vec![(11, 24, 3)]);
        assert_eq!(SMALL.runs("-", 10, 20, true), vec![(11, 24, 4)]);
        assert_eq!(SMALL.runs("é", 0, 0, false), SMALL.runs("?", 0, 0, false)); // outside ASCII: '?'
    }
}
