//! The built-in bitmap fonts (compiled into the binary: no server-side fonts, no font files).
//!
//! `SMALL`: 5 x 9 cells (7 rows above the baseline, 2 below), 6 pixels per character, for the status line, the
//! hint, the menu and the help text; drawn twice side by side it is the bold "WORM" label. `BIG`: bold 11-pixel
//! digits, `%` and `-` for the percent. Each glyph is written as its pixel rows ('#' = ink), top to bottom.

/// A bitmap font: glyph rows per character.
pub struct Font {
    glyphs: &'static [(char, &'static str)],
    /// Pixel rows of every glyph.
    pub height: i32,
    /// Rows above the baseline (the height of a capital letter or digit).
    pub ascent: i32,
    /// Empty columns between two glyphs.
    pub spacing: i32,
}

/// One filled pixel run: x, y, width (height 1).
pub type Run = (i32, i32, i32);

impl Font {
    fn glyph(&self, c: char) -> &'static str {
        let find = |c: char| self.glyphs.iter().find(|g| g.0 == c).map(|g| g.1);
        find(c).or_else(|| find('?')).unwrap_or("")
    }

    fn glyph_width(&self, c: char) -> i32 {
        self.glyph(c).split(' ').next().map_or(0, |r| r.len() as i32)
    }

    /// Width in pixels of `text` (bold adds one column per glyph).
    pub fn width(&self, text: &str, bold: bool) -> i32 {
        let n = text.chars().count() as i32;
        if n == 0 {
            return 0;
        }
        text.chars().map(|c| self.glyph_width(c) + i32::from(bold)).sum::<i32>() + self.spacing * (n - 1)
    }

    /// The ink of `text` with its top-left corner at (x, y), as horizontal pixel runs.
    pub fn runs(&self, text: &str, x: i32, y: i32, bold: bool) -> Vec<Run> {
        let mut out = Vec::new();
        let mut pen = x;
        for c in text.chars() {
            let g = self.glyph(c);
            for (row, bits) in g.split(' ').enumerate() {
                let bytes = bits.as_bytes();
                let mut col = 0;
                while col < bytes.len() {
                    if bytes[col] == b'#' {
                        let start = col;
                        while col < bytes.len() && bytes[col] == b'#' {
                            col += 1;
                        }
                        let len = (col - start) as i32 + i32::from(bold); // bold: the same run one pixel wider
                        out.push((pen + start as i32, y + row as i32, len));
                    } else {
                        col += 1;
                    }
                }
            }
            pen += self.glyph_width(c) + i32::from(bold) + self.spacing;
        }
        out
    }
}

